import assert from 'node:assert/strict';
import { createServer } from 'vite';
const server = await createServer({ configFile: false, server: { middlewareMode: true, hmr: false, ws: false }, appType: 'custom' });
const originalFetch = globalThis.fetch;
try {
  const { withinGeography, geographicError } = await server.ssrLoadModule('/src/geography.js');
  assert.equal(withinGeography({latitude:0,longitude:-179}, {latitude:0,longitude:180,radius_km:150}), true);
  assert.equal(withinGeography({latitude:0,longitude:170}, {latitude:0,longitude:180,radius_km:150}), false);
  assert.equal(withinGeography({latitude:0,longitude:-179}, {south:-1,north:1,west:178,east:-178}), true);
  assert.equal(withinGeography({latitude:null,longitude:null}, {latitude:0,longitude:0,radius_km:1}), false);
  assert.equal(withinGeography({latitude:89.9,longitude:90}, {latitude:90,longitude:-90,radius_km:20}), true);
  assert.ok(geographicError({latitude:0}));
  assert.ok(geographicError({latitude:0,longitude:0,radius_km:-1}));
  const { formatMeasurement, formatCoordinate } = await server.ssrLoadModule('/src/format.js');
  assert.equal(formatMeasurement(.0481277), '0.05');
  assert.equal(formatMeasurement(.0000123), '0.00001');
  assert.equal(formatMeasurement(null), 'Not available');
  assert.equal(formatCoordinate(12.34567), '12.3457');
  const { collectSearch, collectAnalyses } = await server.ssrLoadModule('/src/exportResults.js');
  const urls=[];
  globalThis.fetch = async url => {
    const parsed = new URL(url, 'http://localhost'); urls.push(parsed);
    const offset=Number(parsed.searchParams.get('offset'));
    return { ok:true, json: async()=>({ total:205, items:Array.from({length:Math.min(100,205-offset)},(_,i)=>({id:`ISS001-E-${offset+i}`})) }) };
  };
  const records=await collectSearch({satellite:'true',latitude:'0',longitude:'180',radius_km:'150'},new Set(['ISS001-E-1']));
  assert.equal(records.length,205);
  assert.deepEqual(urls.map(u=>u.searchParams.get('offset')),['0','100','200']);
  assert.ok(urls.every(u=>u.searchParams.get('radius_km')==='150' && u.searchParams.get('satellite')==='true' && u.searchParams.get('photo_ids')==='ISS001-E-1'));
  globalThis.fetch = async()=>({ok:true,json:async()=>({id:'ISS001-E-1',metadata:{},predictions:{chlor_a:{value:.123456789}}})});
  const analyses=await collectAnalyses(['ISS001-E-1'],{});
  assert.match(analyses[0].original_url,/mission=ISS001&roll=E&frame=1/);
  assert.equal(analyses[0].predictions.chlor_a.value,.123456789);
  globalThis.fetch = async()=>({ok:true,json:async()=>({total:2,items:[]})});
  await assert.rejects(()=>collectSearch({}),/before all results/);
  globalThis.fetch = async()=>({ok:false,json:async()=>({detail:'Unavailable'})});
  await assert.rejects(()=>collectAnalyses(['ISS001-E-2'],{}),/Unavailable/);
  const { sharedLogRange } = await server.ssrLoadModule('/src/SatelliteComparison.jsx');
  assert.deepEqual(sharedLogRange([-1,1], {grid_log10:[[-2,null,2]]}), [-2,2]);
  assert.deepEqual(sharedLogRange([-1,1], {grid_log10:[[-2,null,2]]}, false), [-1,1]);
  assert.deepEqual(sharedLogRange([-1,1], null), [-1,1]);
  const { satelliteReference } = await server.ssrLoadModule('/src/PredictionSummary.jsx');
  assert.equal(satelliteReference({predictions:{chlor_a:{value:9,satellite:{targets:{chlor_a:{value:.31}}}}}}, 'chlor_a').value, .31);
  assert.equal(satelliteReference({predictions:{}}, 'kd_490'), undefined);
  const { loadNativeCatalog, nativePhotoList, loadNativePhoto, withinSatelliteError } = await server.ssrLoadModule('/src/nativeCatalog.js');
  const agreement = {targets:{chlor_a:{mean_absolute_percentage_error:25},kd_490:{mean_absolute_percentage_error:30}}};
  assert.equal(withinSatelliteError(agreement, {maxError:'25',errorTarget:'chlor_a'}), true);
  assert.equal(withinSatelliteError(agreement, {maxError:'25',errorTarget:'both'}), false);
  assert.equal(withinSatelliteError(agreement, {maxError:'30',errorTarget:'both'}), true);
  assert.equal(withinSatelliteError(agreement, {maxError:'29.999',errorTarget:'kd_490'}), false);
  assert.equal(withinSatelliteError(null, {maxError:'25'}), false);
  assert.equal(withinSatelliteError(null, {maxError:''}), true);
  assert.equal(withinSatelliteError(agreement, {maxError:'-1'}), false);
  assert.equal(withinSatelliteError(agreement, {maxError:'invalid'}), false);
  assert.equal(withinSatelliteError({targets:{chlor_a:{mean_absolute_percentage_error:0}}}, {maxError:'0',errorTarget:'chlor_a'}), true);
  const detail = {id:'ISS999-E-1',metadata:{},predictions:{chlor_a:{value:.123456789}}};
  const bytes = new TextEncoder().encode(JSON.stringify(detail));
  const digest = Array.from(new Uint8Array(await crypto.subtle.digest('SHA-256',bytes)),v=>v.toString(16).padStart(2,'0')).join('');
  let detailReads=0;
  globalThis.fetch = async url => {
    if(url.endsWith('/index.json'))return {ok:true,json:async()=>({schema:'appa-native-catalog-v1',run:{state:'running'},photos:[
      {id:detail.id,split:'train',mission:'ISS999',captured_at:'2025-01-01',latitude:0,longitude:0,entry:{satellite_agreement:agreement,detail_url:'/native-scaleup/details/test.json',detail_sha256:digest}},
      {id:'ISS999-E-2',split:'validation',mission:'ISS999',captured_at:'2025-01-02',latitude:0,longitude:0,entry:{detail_url:'/native-scaleup/details/corrupt.json',detail_sha256:'bad'}}]})};
    detailReads++;return {ok:true,arrayBuffer:async()=>bytes.buffer};
  };
  await loadNativeCatalog();
  assert.equal(nativePhotoList({}).total,2,'Latest catalog excludes older pilot photos');
  assert.equal(nativePhotoList({maxError:'30',errorTarget:'both'}).total,1);
  assert.equal(nativePhotoList({maxError:'25',errorTarget:'both'}).total,0);
  assert.equal(detailReads,0,'Catalog must not preload every photo detail');
  assert.deepEqual(nativePhotoList({q:'ISS999',split:'train'}).items.map(p=>p.id),['ISS999-E-1']);
  assert.deepEqual(nativePhotoList({q:'ISS999',split:'validation'}).items.map(p=>p.id),['ISS999-E-2']);
  assert.equal(nativePhotoList({q:'ISS999',south:1,north:2}).total,0);
  assert.equal((await loadNativePhoto(detail.id)).predictions.chlor_a.value,.123456789);
  await loadNativePhoto(detail.id); assert.equal(detailReads,1,'Repeated detail reads should use the bounded cache');
  await assert.rejects(()=>loadNativePhoto('ISS999-E-2'),/checksum mismatch/);
  const exported=await collectAnalyses([detail.id],loadNativePhoto);
  assert.equal(exported[0].id,detail.id);
  assert.match(exported[0].original_url,/mission=ISS999/);
  console.log('Passed: radius/bounds, date line, poles, missing coordinates, precision, complete paginated exports, NASA links export failures, shared overlay scales and satellite reference values.');
} finally { globalThis.fetch=originalFetch; await server.close(); }
